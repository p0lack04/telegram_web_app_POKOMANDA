import {beforeAll,afterAll,it,expect} from 'vitest';
import {PrismaClient,type User} from '@prisma/client';
import EmbeddedPostgres from 'embedded-postgres';
import {mkdtemp} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createServer} from 'node:net';
import {execFileSync} from 'node:child_process';
import {randomBytes} from 'node:crypto';
import type {FastifyInstance} from 'fastify';
import {buildApp} from '../src/app.js';
import {hashToken} from '../src/services/auth.js';
const origin='http://localhost:5173';
let pg:EmbeddedPostgres,db:PrismaClient,app:FastifyInstance;
let admin:User,lead:User,trainee:User,outsider:User,manager:User;
let shiftId:string,hiddenId:string;
const cookies=new Map<string,string>();
async function fixture(id:number,role:User['role']) {
 const user=await db.user.create({data:{telegramId:BigInt(id),firstName:'Тест',role,isOnboarded:true,accountStatus:'CONFIRMED'}});
 const token=randomBytes(32).toString('base64url');await db.session.create({data:{userId:user.id,tokenHash:hashToken(token),expiresAt:new Date(Date.now()+3600000)}});cookies.set(user.id,`komanda_session=${token}`);return user;
}
const request=(user:User,method:'GET'|'POST'|'PATCH',url:string,payload?:object)=>app.inject({method,url,headers:{origin,cookie:cookies.get(user.id)!},...(payload?{payload}:{})});
beforeAll(async()=>{
 const listener=createServer();await new Promise<void>(r=>listener.listen(0,'127.0.0.1',r));const address=listener.address();if(!address||typeof address==='string')throw Error('port');const port=address.port;await new Promise<void>(r=>listener.close(()=>r()));
 const password=randomBytes(20).toString('hex');const dir=await mkdtemp(join(tmpdir(),'komanda-program-'));
 pg=new EmbeddedPostgres({databaseDir:join(dir,'data'),user:'postgres',password,port,persistent:false,autoRehydrateSymlinks:true,postgresFlags:['-h','127.0.0.1'],onLog:()=>{},onError:()=>{}});
 await pg.initialise();await pg.start();await pg.createDatabase('program');
 const url=`postgresql://postgres:${password}@127.0.0.1:${port}/program`;
 db=new PrismaClient({datasources:{db:{url}}});
 execFileSync(process.execPath,[resolve('../node_modules/prisma/build/index.js'),'migrate','deploy','--schema',resolve('prisma/schema.prisma')],{env:{...process.env,DATABASE_URL:url},stdio:'pipe'});
 app=await buildApp({NODE_ENV:'test',HOST:'127.0.0.1',PORT:3001,DATABASE_URL:url,APP_ORIGIN:origin,TELEGRAM_BOT_TOKEN:'123456:ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijk'},db);
 admin=await fixture(8101,'ADMIN');lead=await fixture(8102,'LEAD');trainee=await fixture(8103,'TRAINEE');outsider=await fixture(8104,'LEAD');manager=await fixture(8105,'LEAD');
 const shift={title:'Программа',startDate:new Date('2027-01-01'),endDate:new Date('2027-01-10')};
 shiftId=(await db.shift.create({data:{...shift,visibility:'ADMIN_LEAD_TRAINEE'}})).id;
 hiddenId=(await db.shift.create({data:shift})).id;
 await db.application.create({data:{shiftId,userId:lead.id,type:'LEAD_RECRUIT',status:'APPROVED'}});
 await db.shiftRole.create({data:{shiftId,userId:manager.id,position:'Ответственный за программу'}});
},120000);
afterAll(async()=>{if(app)await app.close();if(db)await db.$disconnect();if(pg)await pg.stop();},30000);
const base=()=>`/api/shifts/${shiftId}`;
it('proposals require identity, active account, visibility, LEAD and admission',async()=>{
 expect((await app.inject({method:'POST',url:base()+'/program-proposals',headers:{origin},payload:{text:'Текст'}})).statusCode).toBe(401);
 for(const user of [trainee,outsider]) expect((await request(user,'POST',base()+'/program-proposals',{text:'Предложение'})).statusCode).toBe(403);
 expect((await request(lead,'POST',`/api/shifts/${hiddenId}/program-proposals`,{text:'Предложение'})).statusCode).toBe(404);
 await db.user.update({where:{id:lead.id},data:{accountStatus:'PENDING'}});
 expect((await request(lead,'POST',base()+'/program-proposals',{text:'Предложение'})).statusCode).toBe(403);
 await db.user.update({where:{id:lead.id},data:{accountStatus:'CONFIRMED'}});
 expect((await request(lead,'POST',base()+'/program-proposals',{text:' '})).statusCode).toBe(400);
});
it('proposals are paginated, private to author/admin, decisions are atomic and do not edit program',async()=>{
 const result=await request(lead,'POST',base()+'/program-proposals',{text:'Перенести мероприятие'});expect(result.statusCode).toBe(200);const {id}=result.json().proposal;
 expect((await request(outsider,'GET',base()+'/program-proposals')).json().total).toBe(0);
 expect((await request(lead,'GET',base()+'/program-proposals?pageSize=1')).json().items[0].text).toBe('Перенести мероприятие');
 expect((await request(manager,'PATCH',base()+'/program-proposals/'+id,{status:'ACCEPTED'})).statusCode).toBe(403);
 expect((await request(admin,'PATCH',`/api/shifts/${hiddenId}/program-proposals/${id}`,{status:'ACCEPTED'})).statusCode).toBe(404);
 const results=await Promise.all(['ACCEPTED','REJECTED'].map(status=>request(admin,'PATCH',base()+'/program-proposals/'+id,{status})));
 expect(results.map(r=>r.statusCode).sort()).toEqual([200,409]);
 expect(await db.auditLog.count({where:{entityId:id,action:{in:['PROGRAM_PROPOSAL_ACCEPTED','PROGRAM_PROPOSAL_REJECTED']}}})).toBe(1);
 expect(await db.programItem.count({where:{shiftId}})).toBe(0);
});
it('reorder checks permission, locks, cross-shift and stale snapshot; failures roll back',async()=>{
 const data={shiftId,title:'Пункт',type:'EDUCATIONAL' as const,date:new Date('2027-01-01'),startTime:'10:00',endTime:'11:00'};
 const a=await db.programItem.create({data});const b=await db.programItem.create({data});
 const entry=(item:typeof a,sortOrder:number)=>({id:item.id,sortOrder,updatedAt:item.updatedAt.toISOString()});
 const payload={items:[entry(a,10),entry(b,20)]};const url=base()+'/program/reorder';
 expect((await request(lead,'PATCH',url,payload)).statusCode).toBe(403);
 expect((await request(admin,'PATCH',url,{items:[entry(a,1),entry(a,2)]})).statusCode).toBe(400);
 expect((await request(admin,'PATCH',`/api/shifts/${hiddenId}/program/reorder`,payload)).statusCode).toBe(404);
 await db.programItem.update({where:{id:b.id},data:{isLocked:true}});
 expect((await request(admin,'PATCH',url,payload)).statusCode).toBe(409);
 await db.programItem.update({where:{id:b.id},data:{isLocked:false}});
 expect((await request(admin,'PATCH',url,payload)).statusCode).toBe(409);
 expect((await db.programItem.findUniqueOrThrow({where:{id:a.id}})).sortOrder).toBe(0);
 const current=await db.programItem.findMany({where:{shiftId},orderBy:{id:'asc'}});
 const fresh={items:current.map((item,i)=>entry(item,i+5))};
 const results=await Promise.all([request(admin,'PATCH',url,fresh),request(manager,'PATCH',url,fresh)]);
 expect(results.map(r=>r.statusCode).sort()).toEqual([200,409]);
 expect(await db.auditLog.count({where:{shiftId,action:'PROGRAM_REORDERED'}})).toBe(1);
});
